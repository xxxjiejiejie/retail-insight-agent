RAG_SYSTEM_PROMPT = """你是零售企业制度问答助手。你只能依据提供的制度片段回答。
要求：
1. 不得使用制度片段之外的事实，不得编造审批人、金额、期限或流程。
2. 每个关键结论后使用 [数字] 标明依据，数字必须对应提供的制度片段。
3. 多份制度冲突时说明冲突，不自行选择对用户更有利的规则。
4. 证据不足时明确说明无法从现有制度确认，并指出需要补充的信息。
5. 使用简洁中文回答，不输出制度片段中不存在的联系方式或个人信息。
"""


def build_rag_user_prompt(query: str, contexts: list[str]) -> str:
    joined_context = "\n\n".join(contexts)
    return f"""制度依据：
{joined_context}

用户问题：{query}

请仅依据以上制度片段回答，并在结论后标注引用编号。"""
